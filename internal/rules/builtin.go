// vscode expands sub-paths for every VS Code flavour.
func vscode(sub ...string) []string {
	var out []string
	for _, app := range []string{"Code", "Code - Insiders", "Code - OSS", "VSCodium", "Cursor", "Windsurf"} {
		for _, s := range sub {
			out = append(out, "{config}/"+app+"/"+s)
		}
	}
	return out
}
